-- 小组/个人私有 GLB 模型库、建筑绑定与只追加操作日志。
-- 可重复执行；依赖 profiles、group_memberships、planning_spaces 及身份辅助函数。

create table if not exists public.group_model_assets (
  id uuid primary key,
  name text not null check (length(trim(name)) between 1 and 100),
  storage_path text not null unique,
  file_size bigint not null check (file_size > 0 and file_size <= 52428800),
  mime_type text not null default 'model/gltf-binary' check (mime_type = 'model/gltf-binary'),
  scope_kind text not null check (scope_kind in ('group', 'personal')),
  course_id text,
  group_id text references public.course_groups(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  source_space_id text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  check (
    (scope_kind = 'group' and group_id is not null)
    or (scope_kind = 'personal' and group_id is null and owner_id = created_by)
  )
);

create table if not exists public.building_model_bindings (
  id bigint generated by default as identity primary key,
  space_id text not null,
  object_code text not null,
  asset_id uuid not null references public.group_model_assets(id) on delete restrict,
  scope_kind text not null check (scope_kind in ('group', 'personal')),
  group_id text references public.course_groups(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  transform jsonb not null default '{}'::jsonb,
  updated_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (space_id, object_code)
);

create table if not exists public.model_operation_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  actor_id uuid not null references auth.users(id),
  actor_name text not null default '',
  action text not null check (action in ('upload', 'replace', 'restore_white', 'delete')),
  result text not null default 'success',
  scope_kind text not null check (scope_kind in ('group', 'personal')),
  course_id text,
  group_id text,
  owner_id uuid not null references auth.users(id),
  space_id text,
  object_code text,
  asset_id uuid,
  asset_name text,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists idx_group_model_assets_group_created
  on public.group_model_assets(group_id, created_at desc);
create index if not exists idx_group_model_assets_owner_created
  on public.group_model_assets(owner_id, created_at desc);
create index if not exists idx_building_model_bindings_asset
  on public.building_model_bindings(asset_id);
create index if not exists idx_model_operation_events_scope_time
  on public.model_operation_events(group_id, owner_id, occurred_at desc);

create or replace function public.can_access_model_scope(
  p_scope_kind text,
  p_group_id text,
  p_owner_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select auth.uid() is not null and (
    public.current_profile_role() = 'admin'
    or (p_scope_kind = 'personal' and p_owner_id = auth.uid())
    or (
      p_scope_kind = 'group'
      and p_group_id is not null
      and exists (
        select 1
        from public.group_memberships membership
        where membership.group_id = p_group_id
          and membership.student_key = public.current_profile_student_key()
      )
    )
  );
$$;

revoke all on function public.can_access_model_scope(text, text, uuid) from public, anon;
grant execute on function public.can_access_model_scope(text, text, uuid) to authenticated;

alter table public.group_model_assets enable row level security;
alter table public.building_model_bindings enable row level security;
alter table public.model_operation_events enable row level security;

drop policy if exists group_model_assets_select_scope on public.group_model_assets;
create policy group_model_assets_select_scope on public.group_model_assets
for select to authenticated
using (public.can_access_model_scope(scope_kind, group_id, owner_id));

drop policy if exists building_model_bindings_select_scope on public.building_model_bindings;
create policy building_model_bindings_select_scope on public.building_model_bindings
for select to authenticated
using (public.can_access_model_scope(scope_kind, group_id, owner_id));

drop policy if exists model_operation_events_select_scope on public.model_operation_events;
create policy model_operation_events_select_scope on public.model_operation_events
for select to authenticated
using (public.can_access_model_scope(scope_kind, group_id, owner_id));

-- 写操作只允许经过下面的原子 RPC，避免绕过校验或遗漏日志。
revoke all on table public.group_model_assets from anon, authenticated;
