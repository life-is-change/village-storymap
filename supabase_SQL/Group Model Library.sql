revoke all on table public.model_operation_events from anon, authenticated;
grant select on table public.group_model_assets to authenticated;
grant select on table public.building_model_bindings to authenticated;
grant select on table public.model_operation_events to authenticated;

create or replace function public.prevent_model_event_mutation()
returns trigger
language plpgsql
as $$
begin
  raise exception 'MODEL_OPERATION_EVENTS_ARE_APPEND_ONLY';
end;
$$;

drop trigger if exists model_operation_events_no_update on public.model_operation_events;
create trigger model_operation_events_no_update
before update on public.model_operation_events
for each row execute function public.prevent_model_event_mutation();

drop trigger if exists model_operation_events_no_delete on public.model_operation_events;
create trigger model_operation_events_no_delete
before delete on public.model_operation_events
for each row execute function public.prevent_model_event_mutation();

create or replace function public.register_group_model(
  p_asset_id uuid,
  p_name text,
  p_storage_path text,
  p_file_size bigint,
  p_scope_kind text,
  p_group_id text default null,
  p_course_id text default null,
  p_space_id text default null
)
returns public.group_model_assets
language plpgsql
security definer
set search_path = public, storage, pg_temp
as $$
declare
  v_asset public.group_model_assets;
  v_name text := left(trim(coalesce(p_name, '')), 100);
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_scope_kind not in ('group', 'personal') then raise exception 'INVALID_SCOPE'; end if;
  if p_file_size <= 0 or p_file_size > 52428800 then raise exception 'INVALID_FILE_SIZE'; end if;
  if p_storage_path !~ '\.glb$' then raise exception 'GLB_REQUIRED'; end if;
  if v_name = '' then raise exception 'MODEL_NAME_REQUIRED'; end if;
  if not public.can_access_model_scope(p_scope_kind, p_group_id, auth.uid()) then
    raise exception 'MODEL_SCOPE_FORBIDDEN';
  end if;

  insert into public.group_model_assets(
    id, name, storage_path, file_size, scope_kind, course_id, group_id,
    owner_id, source_space_id, created_by
  ) values (
    p_asset_id, v_name, p_storage_path, p_file_size, p_scope_kind, p_course_id,
    case when p_scope_kind = 'group' then p_group_id else null end,
    auth.uid(), p_space_id, auth.uid()
  ) returning * into v_asset;

  insert into public.model_operation_events(
    actor_id, actor_name, action, scope_kind, course_id, group_id, owner_id,
    space_id, asset_id, asset_name, metadata
  ) values (
    auth.uid(), coalesce(public.current_profile_display_name(), ''), 'upload',
    v_asset.scope_kind, v_asset.course_id, v_asset.group_id, v_asset.owner_id,
    v_asset.source_space_id, v_asset.id, v_asset.name,
    jsonb_build_object('storage_path', v_asset.storage_path, 'file_size', v_asset.file_size)
  );

  return v_asset;
end;
$$;

create or replace function public.place_group_model(
  p_asset_id uuid,
  p_space_id text,
  p_object_code text,
  p_transform jsonb default '{}'::jsonb
)
returns public.building_model_bindings
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_asset public.group_model_assets;
  v_binding public.building_model_bindings;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  if trim(coalesce(p_space_id, '')) = '' or trim(coalesce(p_object_code, '')) = '' then
    raise exception 'BUILDING_IDENTITY_REQUIRED';
  end if;

  select * into v_asset from public.group_model_assets where id = p_asset_id;
  if not found then raise exception 'MODEL_NOT_FOUND'; end if;
  if not public.can_access_model_scope(v_asset.scope_kind, v_asset.group_id, v_asset.owner_id) then
    raise exception 'MODEL_SCOPE_FORBIDDEN';
  end if;
  if v_asset.scope_kind = 'group' and not exists (
    select 1 from public.planning_spaces ps
    where ps.id = p_space_id and ps.group_id = v_asset.group_id
  ) then
    raise exception 'MODEL_SPACE_SCOPE_MISMATCH';
  end if;
  if v_asset.scope_kind = 'personal' and not exists (
    select 1 from public.course_personal_spaces personal_space
    where personal_space.id::text = p_space_id
      and personal_space.owner_id = auth.uid()
  ) then
    raise exception 'MODEL_SPACE_FORBIDDEN';
  end if;

  insert into public.building_model_bindings(
    space_id, object_code, asset_id, scope_kind, group_id, owner_id, transform, updated_by
  ) values (
    p_space_id, trim(p_object_code), v_asset.id, v_asset.scope_kind,
    v_asset.group_id, v_asset.owner_id, coalesce(p_transform, '{}'::jsonb), auth.uid()
  )
  on conflict (space_id, object_code) do update set
    asset_id = excluded.asset_id,
    scope_kind = excluded.scope_kind,
    group_id = excluded.group_id,
    owner_id = excluded.owner_id,
    transform = excluded.transform,
    updated_by = auth.uid(),
    updated_at = now()
  returning * into v_binding;

  insert into public.model_operation_events(
    actor_id, actor_name, action, scope_kind, course_id, group_id, owner_id,
    space_id, object_code, asset_id, asset_name, metadata
  ) values (
    auth.uid(), coalesce(public.current_profile_display_name(), ''), 'replace',
    v_asset.scope_kind, v_asset.course_id, v_asset.group_id, v_asset.owner_id,
    p_space_id, trim(p_object_code), v_asset.id, v_asset.name,
    jsonb_build_object('transform', coalesce(p_transform, '{}'::jsonb))
  );

  return v_binding;
end;
$$;

create or replace function public.restore_building_white_model(
  p_space_id text,
  p_object_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_binding public.building_model_bindings;
  v_asset public.group_model_assets;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  select * into v_binding
  from public.building_model_bindings
  where space_id = p_space_id and object_code = trim(p_object_code)
  for update;

  if found then
    if not public.can_access_model_scope(v_binding.scope_kind, v_binding.group_id, v_binding.owner_id) then
      raise exception 'MODEL_SCOPE_FORBIDDEN';
    end if;
    select * into v_asset from public.group_model_assets where id = v_binding.asset_id;
    delete from public.building_model_bindings where id = v_binding.id;
  else
    if exists (
      select 1 from public.course_personal_spaces personal_space
      where personal_space.id::text = p_space_id and personal_space.owner_id = auth.uid()
    ) then
      v_binding.scope_kind := 'personal';
      v_binding.owner_id := auth.uid();
    elsif exists (
      select 1 from public.planning_spaces group_space
      where group_space.id = p_space_id
        and group_space.group_id is not null
        and public.can_access_model_scope('group', group_space.group_id, auth.uid())
    ) then
      select group_space.group_id into v_binding.group_id
      from public.planning_spaces group_space where group_space.id = p_space_id;
      v_binding.scope_kind := 'group';
      v_binding.owner_id := auth.uid();
    else
      raise exception 'MODEL_SPACE_FORBIDDEN';
    end if;
  end if;

  insert into public.model_operation_events(
    actor_id, actor_name, action, scope_kind, course_id, group_id, owner_id,
    space_id, object_code, asset_id, asset_name
  ) values (
    auth.uid(), coalesce(public.current_profile_display_name(), ''), 'restore_white',
    v_binding.scope_kind, v_asset.course_id, v_binding.group_id, v_binding.owner_id,
    p_space_id, trim(p_object_code), v_binding.asset_id, v_asset.name
  );

  return jsonb_build_object('restored', true);
end;
$$;

create or replace function public.delete_group_model(p_asset_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_asset public.group_model_assets;
  v_usage_count integer;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  select * into v_asset from public.group_model_assets where id = p_asset_id for update;
  if not found then raise exception 'MODEL_NOT_FOUND'; end if;
  if not public.can_access_model_scope(v_asset.scope_kind, v_asset.group_id, v_asset.owner_id) then
    raise exception 'MODEL_SCOPE_FORBIDDEN';
  end if;

  select count(*) into v_usage_count
  from public.building_model_bindings
  where asset_id = p_asset_id;
  if v_usage_count > 0 then raise exception 'MODEL_IN_USE:%', v_usage_count; end if;

  insert into public.model_operation_events(
    actor_id, actor_name, action, scope_kind, course_id, group_id, owner_id,
    space_id, asset_id, asset_name, metadata
  ) values (
    auth.uid(), coalesce(public.current_profile_display_name(), ''), 'delete',
    v_asset.scope_kind, v_asset.course_id, v_asset.group_id, v_asset.owner_id,
    v_asset.source_space_id, v_asset.id, v_asset.name,
    jsonb_build_object('storage_path', v_asset.storage_path)
  );

  delete from public.group_model_assets where id = p_asset_id;
  return jsonb_build_object('deleted', true, 'storage_path', v_asset.storage_path);
end;
$$;

